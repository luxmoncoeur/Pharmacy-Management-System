// Import it in phpMyAdmin (Import tab) or run: mysql -u root < database/pharmacy_pms.sql
import { readFileSync, writeFileSync } from 'node:fs';

const read = (name) => readFileSync(new URL(`../database/${name}`, import.meta.url), 'utf8');

const sql = `-- Pharmacy Management System: complete database (schema + sample data).
-- Import in phpMyAdmin (Import tab, no database selected) or run: mysql -u root < database/pharmacy_pms.sql
-- WARNING: re-importing drops and recreates every table in pharmacy_pms.
-- Generated by scripts/build-sql.js from schema.sql and seed.sql; do not edit by hand.

CREATE DATABASE IF NOT EXISTS pharmacy_pms CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pharmacy_pms;
-- Sample dates are relative to today in Philippine time.
SET time_zone = '+08:00';

${read('schema.sql')}
${read('seed.sql')}
`;

writeFileSync(new URL('../database/pharmacy_pms.sql', import.meta.url), sql);
console.log(`database/pharmacy_pms.sql written (${(Buffer.byteLength(sql) / 1024).toFixed(0)} KB).`);
